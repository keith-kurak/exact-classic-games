/// Everything the picture processor needs, built from the art above.
pub struct Art {
    /// Background CHR banks: the field's, and the battle's. Each starts with
    /// the same window tiles, so text indices match in both; the battle bank
    /// swaps the field's terrain for big enemies, as NES RPGs swapped banks.
    pub bg: PatternTable,
    pub bg_battle: PatternTable,
    pub spr: PatternTable,
    /// Background metatiles by map character (field bank, and the cave rock
    /// in the battle bank).
    pub metatiles: HashMap<char, Metatile>,
    /// Enemies (battle bank): size in tiles and their tiles, row by row.
    pub enemies: HashMap<&'static str, Enemy>,
    pub sprites: HashMap<&'static str, Metasprite>,
    pub ui: Ui,
    /// Animated metatiles: frames by map character, swapped like CHR banks.
    pub frames: HashMap<char, Vec<Metatile>>,
    /// Digits as sprites: in colour 3 (healing, green) and colour 2 (damage, red).
    pub digits: HashMap<char, u16>,
    pub digits2: HashMap<char, u16>,
}

pub struct Enemy {
    pub w: usize,
    pub h: usize,
    pub tiles: Vec<u16>,
    /// Each tile's background palette.
    pub palettes: Vec<u8>,
}

/// Window and label tiles, at the same index in every background bank.
pub struct Ui {
    /// Glyphs on window blue: white, and yellow for the characters yellow text uses.
    pub glyphs: HashMap<char, u16>,
    pub yellow: HashMap<char, u16>,
    /// Gauges on the black backdrop, for HP bars under enemies.
    pub clear_bars: [u16; 9],
    pub border: Border,
    /// HP bar tiles for the backdrop (`@` labels), 0–8 pixels filled.
    /// ATB gauge tiles on window blue, 0–8 pixels filled, and (9) a solid
    /// block: a charged segment.
    pub bars: [u16; 10],
}

pub struct Border {
    pub tl: u16,
    pub tr: u16,
    pub bl: u16,
    pub br: u16,
    pub top: u16,
    pub bottom: u16,
    pub left: u16,
    pub right: u16,
    pub fill: u16,
}

fn one(art: &str) -> Tile {
    parse_art(art).2[0]
}

fn metatile(bg: &mut PatternTable, art: &str, palette: u8) -> Metatile {
    let (w, h, tiles) = parse_art(art);
    assert!(w == 2 && h == 2, "a metatile is 16×16");
    Metatile {
        tiles: [bg.add(tiles[0]), bg.add(tiles[1]), bg.add(tiles[2]), bg.add(tiles[3])],
        palette,
    }
}

fn ui(bg: &mut PatternTable) -> Ui {
    // Tile 0 is blank (all backdrop).
    bg.add(Tile::default());
    let corner = one(CORNER);
    let top = one(EDGE_TOP);
    let left = one(EDGE_LEFT);
    let border = Border {
        tl: bg.add(corner),
        tr: bg.add(corner.mirrored()),
        bl: bg.add(corner.flipped()),
        br: bg.add(corner.mirrored().flipped()),
        top: bg.add(top),
        bottom: bg.add(top.flipped()),
        left: bg.add(left),
        right: bg.add(left.mirrored()),
        fill: bg.add(Tile([[1; 8]; 8])),
    };
    let mut glyphs = HashMap::new();
    let mut yellow = HashMap::new();
    let yellow_chars: Vec<char> = "StrikeBlastMendGuardHoundDroneVictoryAttackSlashFireIceCureHealProvokeSteelPotion*%0123456789".chars().collect();
    for (ch, rows) in FONT {
        glyphs.insert(*ch, bg.add(glyph_tile(rows, 3, 1)));
        let _ = &yellow_chars;
        yellow.insert(*ch, bg.add(glyph_tile(rows, 2, 1)));
    }
    let gauge = |n: usize, empty: u8| -> Tile {
        let mut t = Tile([[empty; 8]; 8]);
        for x in 0..8 {
            t.0[2][x] = 3;
            t.0[5][x] = 3;
            for y in 3..5 {
                t.0[y][x] = if x < n { 2 } else { empty };
            }
        }
        t
    };
    // HP bars on the backdrop, in the cave palette: a thick green bar (2)
    // over a dark trough (1).
    let hp_bar = |n: usize| -> Tile {
        let mut t = Tile([[0; 8]; 8]);
        for x in 0..8 {
            for y in 0..4 {
                t.0[y][x] = if x >= n { 1 } else { 2 };
            }
        }
        t
    };
    let mut bars = [0u16; 10];
    let mut clear_bars = [0u16; 9];
    for n in 0..9 {
        bars[n] = bg.add(gauge(n, 1));
        clear_bars[n] = bg.add(hp_bar(n));
    }
    let mut block = Tile([[1; 8]; 8]);
    for y in 1..7 {
        for x in 0..8 {
            block.0[y][x] = if y == 1 || y == 6 { 3 } else { 2 };
        }
    }
    bars[9] = bg.add(block);
    Ui { glyphs, yellow, clear_bars, border, bars }
}

pub fn build() -> Art {
    let mut bg = PatternTable::default();
    let mut spr = PatternTable::default();
    let ui_tiles = ui(&mut bg);

    let mut metatiles = HashMap::new();
    for (ch, art, pal) in [
        ('.', MEADOW, 0),
        (',', THICKET, 0),
        ('T', TREE, 0),
        ('=', PATH, 1),
        ('~', WATER, 2),
        ('#', STONE, 3),
        ('R', ROOF, 1),
        ('W', WALL, 3),
        ('D', DOOR, 1),
        ('F', FENCE, 1),
        ('C', CROPS, 1),
        ('B', BRIDGE, 1),
        ('*', CRYSTAL, 2),
    ] {
        metatiles.insert(ch, metatile(&mut bg, art, pal));
    }

    // The battle bank: the window tiles, the cave rock, then the enemies
    // (64×64).
    let mut bg_battle = PatternTable::default();
    let battle_ui = ui(&mut bg_battle);
    assert_eq!(battle_ui.border.fill, ui_tiles.border.fill, "both banks share the window tiles");
    assert_eq!(battle_ui.clear_bars, ui_tiles.clear_bars);
    for (ch, rock, pal) in [('k', ROCK, 0), ('K', SHARD, 0)] {
        metatiles.insert(ch, metatile(&mut bg_battle, rock, pal));
    }
    let mut enemies = HashMap::new();
    let list: [(&str, &str, &[&str]); 3] = [("drone", DRONE, &DRONE_PAL), ("hound", HOUND, &HOUND_PAL), ("warden", WARDEN, &WARDEN_PAL)];
    for (name, art, pal) in list {
        let (w, h, tiles) = parse_art(art);
        let ids = tiles.into_iter().map(|t| bg_battle.add(t)).collect();
        let palettes = pal.iter().flat_map(|row| row.bytes().map(|b| b - b'0')).collect();
        enemies.insert(name, Enemy { w, h, tiles: ids, palettes });
    }

    let mut sprites = HashMap::new();
    for (name, art, pal) in [
        ("down0", FIELD_DOWN_0, 0),
        ("down1", FIELD_DOWN_1, 0),
        ("up0", FIELD_UP_0, 0),
        ("up1", FIELD_UP_1, 0),
        ("left0", FIELD_LEFT_0, 0),
        ("left1", FIELD_LEFT_1, 0),
        ("villager0", VILLAGER, 0),
        ("villager1", VILLAGER_1, 0),
        ("idle0", THUNDA_IDLE, 0),
        ("strike0", THUNDA_STRIKE, 0),
        ("idle1", TOOTH_IDLE, 1),
        ("strike1", TOOTH_STRIKE, 1),
        ("idle2", CHOCOLAT_IDLE, 2),
        ("strike2", CHOCOLAT_STRIKE, 2),
        ("cast0", THUNDA_CAST, 0),
        ("cast1", TOOTH_CAST, 1),
        ("cast2", CHOCOLAT_CAST, 2),
        ("fireball", FIREBALL, 3),
        ("iceball", ICEBALL, 1),
        ("warden0", WARDEN_FIELD_0, 3),
        ("warden1", WARDEN_FIELD_1, 3),
        ("win0", THUNDA_WIN, 0),
        ("win1", TOOTH_WIN, 1),
        ("win2", CHOCOLAT_WIN, 2),
        ("ko", BATTLE_DOWN, 0),
        ("hand", HAND, 3),
    ] {
        sprites.insert(name, Metasprite::from_art(&mut spr, &art.replace(' ', "."), pal));
    }
    let mut digits = HashMap::new();
    let mut digits2 = HashMap::new();
    for (ch, rows) in FONT.iter().filter(|(c, _)| c.is_ascii_digit()) {
        digits.insert(*ch, spr.add(glyph_tile(rows, 3, 0)));
        digits2.insert(*ch, spr.add(glyph_tile(rows, 2, 0)));
    }

    // Water ripples: four frames, each crest moved two pixels on.
    let (_, _, water) = parse_art(WATER);
    let mut frames = HashMap::new();
    let water_frames: Vec<Metatile> = (0..4)
        .map(|k| {
            let shift = |t: &Tile| -> Tile {
                let mut o = *t;
                for row in o.0.iter_mut() {
                    row.rotate_right((k * 2) % 8);
                }
                o
            };
            Metatile {
                tiles: [bg.add(shift(&water[0])), bg.add(shift(&water[1])), bg.add(shift(&water[2])), bg.add(shift(&water[3]))],
                palette: 2,
            }
        })
        .collect();
    frames.insert('~', water_frames);

    Art { bg, bg_battle, spr, metatiles, enemies, sprites, ui: ui_tiles, frames, digits, digits2 }
}

